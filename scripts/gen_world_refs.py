"""Generate content/world_refs.json: the object and NPC ids the JS world defines.

Object ids, café tables built in a loop, and the levels some objects and NPCs are limited
to only exist at runtime, so this loads web/index.html in headless Chromium and reads
`objects` and `NPCDEF`. Needs: pip install -r requirements-dev.txt; python -m playwright install chromium.
Run after changing placeObjects() or NPCDEF in web/js/content.js:  python scripts/gen_world_refs.py
"""
import json
import os
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from phishverse.content import CONTENT_DIR, world_js_sha256  # noqa: E402

READ_WORLD = """() => ({
  objects: Object.fromEntries(objects.filter(o => o.id).map(o => [o.id, o.levels || null])),
  npcs: Object.fromEntries(NPCDEF.map(n => [n.id, n.levels || null])),
})"""


def read_runtime_world():
    from playwright.sync_api import sync_playwright
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        page.route("**/fonts.googleapis.com/**", lambda r: r.fulfill(status=200, content_type="text/css", body=""))
        page.goto((ROOT / "web" / "index.html").as_uri())
        page.wait_for_function("() => typeof objects !== 'undefined' && objects.length > 0")
        world = page.evaluate(READ_WORLD)
        browser.close()
    return world


def build():
    world = read_runtime_world()
    return {
        "$comment": "GENERATED by scripts/gen_world_refs.py from web/js/content.js. null = present in every level.",
        "source_sha256": world_js_sha256(),
        "objects": dict(sorted(world["objects"].items())),
        "npcs": dict(sorted(world["npcs"].items())),
    }


def main():
    path = os.path.join(CONTENT_DIR, "world_refs.json")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(build(), f, indent=2)
        f.write("\n")
    print(f"Wrote {os.path.relpath(path)}")


if __name__ == "__main__":
    main()
