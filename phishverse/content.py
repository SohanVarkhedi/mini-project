"""
Scenario content: content/levels.json (levels, tasks, encounters, outcome scale),
content/skills.json (skills taxonomy) and content/world_refs.json (object and NPC ids
that exist in the JS world; generated by scripts/gen_world_refs.py).

The server scores decisions from this content only. validate() is shared by
scripts/validate_content.py, the tests and app startup.
"""
import hashlib
import json
import math
import os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT_DIR = os.path.join(BASE, "content")
CONTENT_JS = os.path.join(BASE, "web", "js", "content-data.js")
TRAINING_JS = os.path.join(BASE, "web", "js", "training-data.js")
WORLD_JS = os.path.join(BASE, "web", "js", "content.js")

CHANNELS = {"email", "sms", "call", "chat", "mfa", "object", "person"}
# data-hl targets each channel's artwork renders (engine.js artHTML)
HL_KEYS = {
    "email": {"addr", "link", "body", "attach"},
    "sms": {"addr", "link", "body"},
    "call": {"addr", "body"},
    "chat": {"addr", "body"},
    "mfa": {"loc", "body"},
    "object": {"body"},
    "person": {"body"},
}
CUES = {"urgency", "authority", "reward", "fear", "curiosity", "familiarity", "secrecy", "helpfulness"}
OUTCOME_IDS = {"safe", "acceptable", "false_alarm", "compromise"}
LIMITS = {  # max characters; the UI is designed for phones
    "level.title": 40, "level.topic": 40, "level.blurb": 200, "intro": 200, "talk": 200,
    "task.label": 48, "enc.title": 80, "lesson": 160, "inspect.l": 40, "inspect.c": 160,
    "act.l": 70, "act.fb": 160,
}
MIN_SCENARIOS_PER_SKILL = 2


def read_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def world_js_sha256(path=WORLD_JS):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read().replace(b"\r\n", b"\n")).hexdigest()


# ---------------------------------------------------------------- validation
def validate(levels_doc, skills_doc, world_refs):
    """Return a list of human-readable problems (empty when the content is valid)."""
    errs = []
    err = errs.append

    outcomes = levels_doc.get("outcomes")
    if not isinstance(outcomes, dict) or set(outcomes) != OUTCOME_IDS:
        err(f"outcomes must define exactly {sorted(OUTCOME_IDS)}")
        outcomes = {}
    for oid, o in outcomes.items():
        if not isinstance(o.get("pts"), (int, float)) or not 0 <= o["pts"] <= 1:
            err(f"outcome {oid}: pts must be a number from 0 to 1")
        for k in ("label", "icon", "col"):
            if not o.get(k):
                err(f"outcome {oid}: missing {k}")

    skills = skills_doc.get("skills") or []
    skill_ids = [s.get("id") for s in skills]
    if len(skill_ids) != len(set(skill_ids)):
        err("skills: duplicate skill id")
    for s in skills:
        for k in ("id", "name", "description", "icon"):
            if not s.get(k):
                err(f"skill {s.get('id')}: missing {k}")
    skill_ids = set(skill_ids)
    coverage = {s: 0 for s in skill_ids}

    objs = world_refs.get("objects") or {}
    npcs = world_refs.get("npcs") or {}

    def text(where, key, value):
        if not isinstance(value, str) or not value.strip():
            err(f"{where}: {key} is missing")
        elif len(value) > LIMITS[key]:
            err(f"{where}: {key} is {len(value)} characters (max {LIMITS[key]})")

    levels = levels_doc.get("levels") or []
    if not levels:
        err("no levels")
    level_ids = [L.get("id") for L in levels]
    if len(level_ids) != len(set(level_ids)):
        err("duplicate level id")
    if [L.get("n") for L in levels] != list(range(1, len(levels) + 1)):
        err("level numbers (n) must run 1, 2, 3 ... in order")

    for L in levels:
        lid = L.get("id")
        where = f"level {lid}"
        text(where, "level.title", L.get("title"))
        text(where, "level.topic", L.get("topic"))
        text(where, "level.blurb", L.get("blurb"))
        if not isinstance(L.get("minutes"), int) or L["minutes"] <= 0:
            err(f"{where}: minutes must be a positive whole number")
        st = L.get("start") or {}
        if not (isinstance(st.get("x"), int) and isinstance(st.get("y"), int) and st.get("dir") in ("up", "down", "left", "right")):
            err(f"{where}: start needs x, y and dir")
        intro = L.get("intro")
        if not isinstance(intro, list) or not intro:
            err(f"{where}: intro must be a non-empty list of pages")
        for p in intro or []:
            text(where, "intro", p)

        tasks = L.get("tasks") or []
        task_ids = [t.get("id") for t in tasks]
        if len(task_ids) != len(set(task_ids)):
            err(f"{where}: duplicate task id")
        if not any(t.get("enc") for t in tasks):
            err(f"{where}: needs at least one scenario")
        for t in tasks:
            tid = t.get("id")
            tw = f"{lid}/{tid}"
            text(tw, "task.label", t.get("label"))
            if t.get("after") is not None and (t["after"] not in task_ids or t["after"] == tid):
                err(f"{tw}: after '{t['after']}' is not another task in this level")
            at = t.get("at") or {}
            if len(at) != 1 or not (set(at) <= {"obj", "npc"}):
                err(f"{tw}: at must have exactly one of obj or npc")
            elif "obj" in at:
                ref = objs.get(at["obj"], "missing")
                if ref == "missing":
                    err(f"{tw}: object '{at['obj']}' isn't in world_refs.json")
                elif ref is not None and lid not in ref:
                    err(f"{tw}: object '{at['obj']}' only exists in levels {ref}")
            else:
                ref = npcs.get(at["npc"], "missing")
                if ref == "missing":
                    err(f"{tw}: NPC '{at['npc']}' isn't in world_refs.json")
                elif ref is not None and lid not in ref:
                    err(f"{tw}: NPC '{at['npc']}' only appears in levels {ref}")

            e = t.get("enc")
            if not e:
                talk = t.get("talk")
                if not isinstance(talk, list) or not talk:
                    err(f"{tw}: a task needs either enc (a scenario) or talk (dialogue pages)")
                for p in talk or []:
                    text(tw, "talk", p)
                continue
            if "talk" in t:
                err(f"{tw}: has both talk and enc")
            ch = e.get("ch")
            if ch not in CHANNELS:
                err(f"{tw}: unknown channel '{ch}'")
            text(tw, "enc.title", e.get("title"))
            text(tw, "lesson", e.get("lesson"))
            if not isinstance(e.get("art"), dict) or not e["art"]:
                err(f"{tw}: art is missing")
            legit = e.get("legit", False)
            if not isinstance(legit, bool):
                err(f"{tw}: legit must be true or false")

            sk = e.get("skills")
            if not isinstance(sk, list) or not 1 <= len(sk) <= 2 or len(set(sk)) != len(sk):
                err(f"{tw}: skills must list 1 or 2 different skill ids (primary first)")
            else:
                for s in sk:
                    if s not in skill_ids:
                        err(f"{tw}: unknown skill '{s}'")
                    else:
                        coverage[s] += 1
            cues = e.get("cues")
            if not isinstance(cues, list) or not cues or len(set(cues)) != len(cues) or not set(cues) <= CUES:
                err(f"{tw}: cues must be a non-empty list from {sorted(CUES)}")
            if e.get("difficulty") not in (1, 2, 3):
                err(f"{tw}: difficulty must be 1, 2 or 3")

            insp = e.get("inspect")
            if not isinstance(insp, list) or not insp:
                err(f"{tw}: inspect must list at least one clue")
            for i, s in enumerate(insp or []):
                text(f"{tw} clue {i}", "inspect.l", s.get("l"))
                text(f"{tw} clue {i}", "inspect.c", s.get("c"))
                if not isinstance(s.get("f"), bool):
                    err(f"{tw} clue {i}: f (is it a red flag?) must be true or false")
                if "hl" in s and s["hl"] not in HL_KEYS.get(ch, set()):
                    err(f"{tw} clue {i}: hl '{s['hl']}' isn't valid for {ch} (use {sorted(HL_KEYS.get(ch, []))})")
            if legit and any(s.get("f") for s in insp or []):
                err(f"{tw}: a legit scenario shouldn't have red-flag clues")

            acts = e.get("acts")
            if not isinstance(acts, list) or not 2 <= len(acts) <= 4:
                err(f"{tw}: needs 2 to 4 actions")
                acts = acts if isinstance(acts, list) else []
            outs = [a.get("o") for a in acts]
            for i, a in enumerate(acts):
                aw = f"{tw} action {i}"
                text(aw, "act.l", a.get("l"))
                text(aw, "act.fb", a.get("fb"))
                if a.get("o") not in OUTCOME_IDS:
                    err(f"{aw}: outcome '{a.get('o')}' isn't valid")
                if a.get("o") == "compromise":
                    if a.get("sev") not in (1, 2, 3):
                        err(f"{aw}: a compromise needs sev 1, 2 or 3")
                elif "sev" in a:
                    err(f"{aw}: only compromise actions have sev")
            if "safe" not in outs:
                err(f"{tw}: needs at least one safe action")
            if legit:
                if "false_alarm" not in outs:
                    err(f"{tw}: a legit scenario needs at least one false_alarm action")
                if "compromise" in outs:
                    err(f"{tw}: a legit scenario can't have a compromise action")

    for s, n in sorted(coverage.items()):
        if n < MIN_SCENARIOS_PER_SKILL:
            err(f"skill {s} is tested by {n} scenario(s); needs at least {MIN_SCENARIOS_PER_SKILL}")
    return errs


# ---------------------------------------------------------------- runtime content
class Content:
    """Read-only view of the content the server needs for scoring."""

    def __init__(self, levels_doc, skills_doc, training_doc=None):
        self.training = training_doc or {"simulations": []}
        self.sims = {s["id"]: s for s in self.training["simulations"]}
        self.outcomes = levels_doc["outcomes"]
        self.levels = {L["id"]: L for L in levels_doc["levels"]}
        self.level_ids = [L["id"] for L in levels_doc["levels"]]
        self.skills = skills_doc["skills"]

    def level(self, level_id):
        return self.levels.get(level_id)

    def scored_tasks(self, level_id):
        L = self.levels.get(level_id)
        return [t for t in L["tasks"] if t.get("enc")] if L else []

    def scored_task(self, level_id, task_id):
        for t in self.scored_tasks(level_id):
            if t["id"] == task_id:
                return t
        return None

    def score(self, outcomes):
        """Same formula as the game (engine.js summary): mean points x 100, rounded half up."""
        if not outcomes:
            return 0, 1
        total = 0
        for o in outcomes:
            total += self.outcomes[o]["pts"]
        score = math.floor(total / len(outcomes) * 100 + 0.5)
        return score, 3 if score >= 90 else 2 if score >= 70 else 1


def read_training(content_dir):
    path = os.path.join(content_dir, "training.json")
    return read_json(path) if os.path.exists(path) else {"simulations": []}


def validate_all(content_dir=CONTENT_DIR):
    """Every content check: levels + skills + world refs, then training simulations."""
    from .training import validate as validate_training
    levels_doc = read_json(os.path.join(content_dir, "levels.json"))
    skills_doc = read_json(os.path.join(content_dir, "skills.json"))
    refs = read_json(os.path.join(content_dir, "world_refs.json"))
    problems = validate(levels_doc, skills_doc, refs)
    problems += validate_training(read_training(content_dir), [s["id"] for s in skills_doc.get("skills", [])],
                                  set(refs.get("npcs") or {}))
    return problems


def load(content_dir=CONTENT_DIR, check=True):
    levels_doc = read_json(os.path.join(content_dir, "levels.json"))
    skills_doc = read_json(os.path.join(content_dir, "skills.json"))
    if check:
        problems = validate_all(content_dir)
        if problems:
            raise RuntimeError("Invalid content in " + content_dir + ":\n  " + "\n  ".join(problems))
    return Content(levels_doc, skills_doc, read_training(content_dir))


# ---------------------------------------------------------------- web/js/content-data.js
def render_training_js(content_dir=CONTENT_DIR):
    """Full simulations WITH answers, for demo mode only (web/index.html opened as a file). The portal
    loads this file only when there is no server; local mode never fetches it."""
    body = json.dumps(read_training(content_dir), ensure_ascii=False, separators=(",", ":"))
    return ("/* GENERATED by scripts/build_content.py from content/training.json. Demo mode only: contains answers. */\n"
            f"window.PV_TRAINING_FULL={body};\n")


def render_content_js(content_dir=CONTENT_DIR):
    """The script demo mode loads (file:// pages can't fetch JSON)."""
    levels_doc = read_json(os.path.join(content_dir, "levels.json"))
    skills_doc = read_json(os.path.join(content_dir, "skills.json"))
    from .demo import demo_data  # sample sessions for demo mode
    from .training import metadata
    data = {"outcomes": levels_doc["outcomes"], "levels": levels_doc["levels"], "skills": skills_doc["skills"],
            "training": metadata(read_training(content_dir)),  # no answers: those stay on the server
            "demo": demo_data(Content(levels_doc, skills_doc))}
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    return ("/* GENERATED by scripts/build_content.py from content/*.json. Do not edit by hand. */\n"
            f"window.PV_CONTENT={body};\n")
